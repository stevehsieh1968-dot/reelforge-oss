// 範本的說書人出鏡場景，換算到實際場景數（例如 10 段範本做成 6 個場景）
export function narratorScenes(tpl, n) {
  if (!tpl) return [];
  const out = new Set();
  tpl.scenes.forEach((s, i) => {
    if (s.narrator) out.add(i === tpl.scenes.length - 1 ? n - 1 : Math.min(n - 1, Math.round((i * (n - 1)) / (tpl.scenes.length - 1))));
  });
  return [...out];
}

export function getTemplate(id) {
  return TEMPLATES.find((t) => t.id === id) || null;
}
